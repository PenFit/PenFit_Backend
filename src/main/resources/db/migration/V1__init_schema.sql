CREATE TABLE financial_profiles (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT      NOT NULL,
    age_band             VARCHAR(20) NOT NULL,
    occupation_type      VARCHAR(30) NOT NULL,
    monthly_salary       BIGINT      NOT NULL,
    living_expense_band  VARCHAR(30) NOT NULL,
    asset_band           VARCHAR(30) NOT NULL,
    debt_band            VARCHAR(30) NOT NULL,
    emergency_fund_band  VARCHAR(30) NOT NULL,
    monthly_savings      BIGINT      NOT NULL,
    current_investment   BIGINT      NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_financial_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_financial_profiles_user UNIQUE (user_id),
    CONSTRAINT ck_financial_profiles_age_band CHECK (age_band IN
        ('AGE_23_25', 'AGE_26_28', 'AGE_29_31', 'AGE_32_34')),
    CONSTRAINT ck_financial_profiles_occupation CHECK (occupation_type IN
        ('REGULAR_EMPLOYEE', 'CONTRACT_EMPLOYEE', 'FREELANCER', 'SELF_EMPLOYED',
         'PUBLIC_OFFICIAL', 'UNEMPLOYED', 'OTHER')),
    CONSTRAINT ck_financial_profiles_living CHECK (living_expense_band IN
        ('LIVING_LE_1M', 'LIVING_GT_1M_LE_1_5M', 'LIVING_GT_1_5M_LE_2M', 'LIVING_GT_2M')),
    CONSTRAINT ck_financial_profiles_asset CHECK (asset_band IN
        ('ASSET_LT_10M', 'ASSET_10M_30M', 'ASSET_30M_50M', 'ASSET_GE_50M')),
    CONSTRAINT ck_financial_profiles_debt CHECK (debt_band IN
        ('DEBT_NONE', 'DEBT_LT_10M', 'DEBT_10M_30M', 'DEBT_GE_30M')),
    CONSTRAINT ck_financial_profiles_emergency CHECK (emergency_fund_band IN
        ('EMERGENCY_LT_1M', 'EMERGENCY_1M_3M', 'EMERGENCY_3M_5M', 'EMERGENCY_GE_5M')),
    CONSTRAINT ck_financial_profiles_amounts CHECK (
        monthly_salary >= 0 AND monthly_savings >= 0 AND current_investment >= 0)
);

