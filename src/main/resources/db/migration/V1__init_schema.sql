CREATE TABLE pension_products (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_type     VARCHAR(20)   NOT NULL,
    provider_name     VARCHAR(50)   NOT NULL,
    product_name      VARCHAR(100)  NOT NULL,
    account_type      VARCHAR(30)   NOT NULL,
    product_type      VARCHAR(30)   NOT NULL,
    summary           TEXT          NOT NULL,
    fee_min_rate      NUMERIC(6, 4) NOT NULL,
    fee_max_rate      NUMERIC(6, 4) NOT NULL,
    investment_scope  VARCHAR(100)  NOT NULL,
    official_url      VARCHAR(500)  NOT NULL,
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
    data_source       VARCHAR(100)  NOT NULL,
    reference_date    DATE          NOT NULL,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_pension_products_name UNIQUE (provider_name, product_name),
    CONSTRAINT ck_pension_products_provider_type CHECK (provider_type IN ('BANK', 'SECURITIES', 'INSURANCE')),
    CONSTRAINT ck_pension_products_account_type CHECK (account_type IN
        ('PENSION_SAVINGS_FUND', 'INDIVIDUAL_IRP', 'PENSION_SAVINGS_INSURANCE')),
    CONSTRAINT ck_pension_products_product_type CHECK (product_type IN
        ('FUND_ACCOUNT', 'IRP_ACCOUNT', 'INSURANCE_PRODUCT')),
    CONSTRAINT ck_pension_products_type_mapping CHECK (
        (product_type = 'FUND_ACCOUNT' AND account_type = 'PENSION_SAVINGS_FUND') OR
        (product_type = 'IRP_ACCOUNT' AND account_type = 'INDIVIDUAL_IRP') OR
        (product_type = 'INSURANCE_PRODUCT' AND account_type = 'PENSION_SAVINGS_INSURANCE')),
    CONSTRAINT ck_pension_products_fee CHECK (fee_min_rate >= 0 AND fee_max_rate >= fee_min_rate)
);
CREATE INDEX ix_pension_products_account_type ON pension_products (account_type, is_active);

